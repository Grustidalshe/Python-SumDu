# Перетворення словника на DataFrame
df = pd.DataFrame.from_dict(
    students, 
    orient='index',
    columns=['Прізвище', 'Ім\'я', 'Адреса', 'Школа', 'Клас', 
             'Оцінка', 'Проекти', 'Години', 'Вартість_курсу']
)
