df['Оцінка_за_проект'] = (df['Оцінка'] / df['Проекти']).round(2)
print("\nСередня оцінка за кожен проект:")
print(df[['Прізвище', 'Ім\'я', 'Оцінка', 'Проекти', 'Оцінка_за_проект']].head(5))

# ФІЛЬТРАЦІЯ ДАНИХ

print("\n" + "="*80)
