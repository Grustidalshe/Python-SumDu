avg_by_school = df.groupby('Школа')['Оцінка'].mean().round(2)
print(avg_by_school)

print("\nСередня кількість проектів по класах:")
avg_projects_by_class = df.groupby('Клас')['Проекти'].mean().round(2)
print(avg_projects_by_class)

print("\nСередня кількість годин та вартість курсу по школах:")
avg_by_school_multi = df.groupby('Школа')[['Години', 'Вартість_курсу', 'Оцінка']].mean().round(2)
print(avg_by_school_multi)

# ДОДАТКОВІ ОПЕРАЦІЇ АГРЕГАЦІЇ

print("\n" + "="*80)
print("9. ДОДАТКОВІ ОПЕРАЦІЇ АГРЕГАЦІЇ")
print("="*80)

# Максимальна загальна вартість навчання по школах
print("Максимальна загальна вартість навчання по школах:")
max_cost_by_school = df.groupby('Школа')['Загальна_вартість'].max()
print(max_cost_by_school)

# Кількість учнів у кожній школі
print("\nКількість учнів у кожній школі:")
students_count = df.groupby('Школа').size()
print(students_count)

# Кількість унікальних класів у кожній школі
print("\nКількість унікальних класів у кожній школі:")
unique_classes = df.groupby('Школа')['Клас'].nunique()
print(unique_classes)

# Агрегація з кількома функціями
print("\nКомплексна агрегація по школах:")
agg_stats = df.groupby('Школа').agg({
    'Оцінка': ['mean', 'min', 'max'],
    'Проекти': ['sum', 'mean'],
    'Загальна_вартість': ['max', 'sum']
}).round(2)
print(agg_stats)

