sorted_by_projects = df.sort_values('Проекти', ascending=False)
print(sorted_by_projects[['Прізвище', 'Ім\'я', 'Проекти', 'Години']].head(5))

print("\nСортування за школою та класом:")
sorted_by_school = df.sort_values(['Школа', 'Клас'], ascending=[True, False])
print(sorted_by_school[['Прізвище', 'Ім\'я', 'Школа', 'Клас']])

# ГРУПУВАННЯ ДАНИХ ТА СЕРЕДНЄ ЗНАЧЕННЯ

print("\n" + "="*80)
print("8. ГРУПУВАННЯ ДАНИХ ТА СЕРЕДНЄ ЗНАЧЕННЯ")
